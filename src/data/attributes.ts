export type AttributeKind = "Standard" | "My Attribute";
export type AttributeDataType = "Text" | "Number" | "Boolean" | "Date";

export type Attribute = {
  id: string;
  name: string;
  apiName: string;
  kind: AttributeKind;
  dataType: AttributeDataType;
  description: string;
  createdBy: string;
  createdOn: string; // ISO
  /** Display label under name for some custom attrs (e.g. user_id → User ID). */
  displayName?: string;
  sampleValues: string[];
  /** Regex patterns shown under Store Data Config (custom only). */
  unmaskedList?: string[];
};

function iso(y: number, m: number, d: number) {
  return new Date(Date.UTC(y, m - 1, d)).toISOString();
}

